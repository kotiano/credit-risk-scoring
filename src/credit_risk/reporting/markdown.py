"""Minimal Markdown rendering helpers for generated reports (no extra dependencies)."""

from __future__ import annotations

import math
from collections.abc import Sequence

import numpy as np
import pandas as pd


def _fmt(value: object, float_fmt: str, explicit: bool = False) -> str:
    if value is None or value is pd.NA:
        return ""
    if isinstance(value, bool | np.bool_):
        return str(bool(value))
    if isinstance(value, int | np.integer):
        return format(int(value), float_fmt) if explicit else str(value)
    if isinstance(value, float | np.floating):
        value = float(value)
        if math.isnan(value):
            return ""
        return format(value, float_fmt)
    return str(value).replace("|", "\\|")


def df_to_markdown(
    df: pd.DataFrame,
    float_fmt: str = ",.4f",
    index: bool = False,
    formats: dict[str, str] | None = None,
) -> str:
    """Render a DataFrame as a GitHub-flavoured Markdown table."""
    formats = formats or {}
    frame = df.reset_index() if index else df
    headers = [str(c) for c in frame.columns]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in frame.itertuples(index=False):
        cells = [
            _fmt(v, formats.get(col, float_fmt), col in formats)
            for col, v in zip(headers, row, strict=True)
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def bullet_list(items: Sequence[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


